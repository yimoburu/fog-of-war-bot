// Static integrity only; no child processes or Python execution.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, lstatSync } from 'node:fs';
import { createHash } from 'node:crypto';

const upstream = {
  'baseline.py': 'b2b9bfcde789a7c8bd86badd2c0c34d7cc243a8df1a1d75276acabd569498c3d',
  'referee.py': '2f82ac292bfad29bcb2d701b73c060d1ca8281378b4598f08a620fe5c97255be',
  'requirements.txt': '391e529739e99dc63461425af4ad7afb10d89aa275922928ceb8e2f5dffa7149',
  'test_uniform_random.py': '60cd5e79fd17b2c24feaa29d7461a08406f5a3401693149b7b8acda5497f842a',
  'uniform_random.py': 'a9d2d69c1893652dae938c596be59fc16fdf1edba3ccf491d9cf2c92d75b514a',
};
const generated = ['README.md', 'SOURCES.md', 'bot.py', 'evaluate.py',
  'package.test.mjs', 'package_submission.py', 'run.sh', 'test_bot.py',
  'belief.py', 'search.py', 'fast_observation.py', 'risk_model.py', 'risk_model.json',
  'legacy_bot.py', 'arena_eval.py', 'profile_resources.py',
  'test_belief.py', 'test_search.py', 'test_arena_eval.py'];
const runtime = ['bot.py', 'belief.py', 'search.py', 'fast_observation.py', 'risk_model.py', 'risk_model.json',
  'referee.py', 'uniform_random.py', 'run.sh', 'requirements.txt', 'SOURCES.md'];
const url = name => new URL(name, import.meta.url);
const bytes = name => readFileSync(url(name));

test('exact upstream hashes, bounded development files and runtime payload', () => {
  let added = 0;
  for (const name of [...Object.keys(upstream), ...generated]) {
    assert.ok(lstatSync(url(name)).isFile(), name);
    const data = bytes(name);
    assert.ok(data.length, name);
    if (upstream[name]) {
      assert.equal(createHash('sha256').update(data).digest('hex'), upstream[name], name);
    } else added += data.length;
  }
  assert.ok(added <= 200000, `Generated bytes: ${added}`);
  // Submission size applies to the exact runtime manifest, excluding local
  // tests, evaluation tools, the baseline opponent and development README.
  const payload = runtime.reduce((total, name) => total + bytes(name).length, 0);
  assert.ok(payload <= 250000, `Runtime payload bytes: ${payload}`);
});

test('launcher and explicit runtime manifest', () => {
  assert.equal(bytes('run.sh').toString(), '#!/usr/bin/env bash\nset -euo pipefail\ncd -- "$(dirname -- "${BASH_SOURCE[0]}")"\nexec python3 -u bot.py --risk-policy learned --search-ms 600 --particles 256 --worlds 6 --depth 4 --nodes 120000 "$@"\n');
  const match = bytes('package_submission.py').toString().match(/RUNTIME_FILES = \(([\s\S]*?)\)/);
  assert.ok(match);
  assert.deepEqual([...match[1].matchAll(/'([^']+)'/g)].map(m => m[1]), runtime);
  assert.match(bytes('package_submission.py').toString(), /^LIMIT = 250000$/m);
});
